"""Общие качества, которые не образуют отдельный пробел в квалификации."""

import re


def generic_autonomy(text):
    normalized = ' '.join(text.casefold().split()).strip(' .;')
    return re.fullmatch(
        r'самостоятельность(?: в решении задач)?|'
        r'(?:умение|способность|готовность) (?:работать самостоятельно|самостоятельно работать)'
        r'(?: с минимальной поддержкой)?|самостоятельное решение задач',
        normalized,
    ) is not None
